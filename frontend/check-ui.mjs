import {JSDOM} from 'jsdom';
import React from 'react';
import {createRoot} from 'react-dom/client';
import {act} from 'react';
import assert from 'node:assert/strict';
import App from './test-dist/App.js';
const dom=new JSDOM('<div id="root"></div>',{url:'http://localhost'});
Object.assign(globalThis,{window:dom.window,document:dom.window.document,localStorage:dom.window.localStorage,IS_REACT_ACT_ENVIRONMENT:true});
const calls=[];
const records=[{session_id:'s1',name:'Driver A / S1',acquisition:'drive1',report:{samples:1000}},{session_id:'s2',name:'Driver B / S2',acquisition:'drive2'}];
const models=Array.from({length:7},(_,i)=>({model_id:'m'+i,family_name:'TCN '+i,kind:'tcn',window:35,version:1}));
globalThis.fetch=async(url,opts={})=>{const body=opts.body&&typeof opts.body==='string'?JSON.parse(opts.body):null;calls.push({url,body});let data=[];
if(url==='/api/datasets')data=records;
if(url==='/api/models')data=models;
if(url==='/api/models/attach')data={...models.find(m=>m.model_id===body.model_id),evaluation_roles:['exploration']};
if(url==='/api/pipeline/simulate')data={metrics:{fused_drift_pct:12,evaluation_mode:'exploration',blackout_duration_s:30,blackout_start_s:300,blackout_end_s:330},trajectories:{ground_truth:[[1,1],[1.1,1.1]],fused:[[1,1],[1.11,1.1]],ins_raw:[[1,1],[1.15,1.12]]}};
if(url==='/api/pipeline/train')data={job_id:'j1'};
if(url==='/api/dataset/upload')data={session_id:'s3'};
return {ok:true,json:async()=>data};};
const root=createRoot(document.getElementById('root'));
const visible=el=>!el.closest('[hidden]');
const button=text=>[...document.querySelectorAll('button')].find(el=>visible(el)&&el.textContent.trim()===text);
const click=async el=>{assert(el,'Control exists');await act(async()=>el.click());};
const select=async(el,v)=>{await act(async()=>{el.value=v;el.dispatchEvent(new dom.window.Event('change',{bubbles:true}))})};
await act(async()=>root.render(React.createElement(App)));
assert(document.body.textContent.includes('Your recordings'));
await click(button('Test this'));
let selects=[...document.querySelectorAll('select')].filter(visible);
assert.equal(selects[1].options.length,8,'All saved models are available');
assert(button('Run test & view results').disabled);
await select(selects[1],'m6');
assert(!button('Run test & view results').disabled);
await click(button('Run test & view results'));
assert([...document.querySelectorAll('h1')].find(visible).textContent==='Test results');
assert.equal(calls.find(c=>c.url==='/api/pipeline/simulate').body.session_id,'s1');
await click(button('Back to test setup'));
selects=[...document.querySelectorAll('select')].filter(visible);
assert.equal(selects[1].value,'m6','Model selection persists across pages');
await select(selects[0],'s2');
assert(button('Run test & view results').disabled,'Changing recording clears attached model');
await click(button('Data'));
const roleSelect=[...document.querySelectorAll('label')].find(el=>el.textContent.startsWith('Training role')&&el.querySelector('select')).querySelector('select');
await select(roleSelect,'train');
await click(button('Train'));
assert(!button('Train & save').disabled);
const parent=[...document.querySelectorAll('label')].find(el=>el.textContent.startsWith('Start from')).querySelector('select');
await select(parent,'m0');
await click(button('Continue training'));
const payload=calls.find(c=>c.url==='/api/pipeline/train').body;
assert.equal(payload.mode,'continue');assert.equal(payload.parent_id,'m0');assert.equal(payload.replay,true);assert.equal(payload.assignments[0].role,'train');
await click(button('More'));await click(button('Open engine diagnostics'));assert(document.querySelector('h1'));
await act(async()=>root.unmount());
console.log('PASS: data → test → results, model gating, all versions, selection persistence, recording reset, continued training payload, diagnostics.');
